import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, expect, it } from "vitest";

import { cachedHeroImage } from "../../../../demos/blog/src/utils/hero-image-cache.js";
import { heroImageSources } from "../../../../demos/blog/src/utils/hero-slides.js";

let directory: string;
beforeEach(async () => {
	directory = await mkdtemp(join(tmpdir(), "hero-cache-"));
});
afterEach(async () => {
	await rm(directory, { recursive: true, force: true });
});

it("reuses generated bytes and coalesces simultaneous requests", async () => {
	let generations = 0;
	const generate = async () => {
		generations++;
		return new Uint8Array([1, 2, 3]);
	};
	const result = await Promise.all([
		cachedHeroImage(directory, "cover.png", 960, generate),
		cachedHeroImage(directory, "cover.png", 960, generate),
	]);
	await cachedHeroImage(directory, "cover.png", 960, generate);
	expect(generations).toBe(1);
	expect([...result[0]!]).toEqual([1, 2, 3]);
	await cachedHeroImage(directory, "cover.png", 1600, generate);
	expect(generations).toBe(2);
});
it("recovers from a failed transform and never caches failed bytes", async () => {
	await expect(
		cachedHeroImage(directory, "cover.png", 960, async () => {
			throw new Error("decode failed");
		}),
	).rejects.toThrow("decode failed");
	expect([
		...(await cachedHeroImage(directory, "cover.png", 960, async () => new Uint8Array([7]))),
	]).toEqual([7]);
});
it("optimizes local uploads without proxying remote images or animated files", () => {
	expect(heroImageSources("/_emdash/api/media/file/revision.png")?.src).toBe(
		"/covers/revision.png.webp?w=1600",
	);
	expect(heroImageSources("https://remote.example/image.png")).toBeNull();
	expect(heroImageSources("/_emdash/api/media/file/animated.gif")).toBeNull();
});
